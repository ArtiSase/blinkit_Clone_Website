// Helper: get products by category
export const getProductsByCategory = (categoryId) => {
  if (categoryId === 'all') return products;
  return products.filter((p) => p.category === categoryId);
};

// Helper: search products
export const searchProducts = (query) => {
  const q = query.toLowerCase().trim();
  if (!q) return products;
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q)
  );
};

// Helper: get product by id
export const getProductById = (id) => products.find((p) => p.id === Number(id));

// Helper: get related products (same category, exclude current)
export const getRelatedProducts = (product, count = 6) =>
  products.filter((p) => p.category === product.category && p.id !== product.id).slice(0, count);
